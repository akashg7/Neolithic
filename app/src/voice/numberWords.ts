/**
 * Reverse mapping from Marathi word to numeric value.
 * Includes official spellings and common regional variations.
 */
export const WORD_TO_NUMBER_MAP: Record<string, number> = (() => {
  const map: Record<string, number> = {};

  // 0 to 99 base words
  MARATHI_0_TO_99.forEach((word, idx) => {
    map[word] = idx;
  });

  // Common alternate forms
  map['एकेचाळीस'] = 41;
  map['सेहेचाळीस'] = 46;
  map['बासष्ठ'] = 62;
  map['छासष्ठ'] = 66;

  // Hundreds
  Object.entries(MARATHI_HUNDREDS).forEach(([numStr, word]) => {
    map[word] = parseInt(numStr, 10);
  });
  map['एकशे'] = 100;

  // Scales
  map['हजार'] = 1000;
  map['लाख'] = 100000;
  map['कोटी'] = 10000000;

  return map;
})();

